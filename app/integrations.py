"""Contratos futuros. Nenhum deles é registrado como ferramenta disponível na v0.1."""

from typing import Protocol


class DesktopAdapter(Protocol):
    async def execute(self, tool: str, arguments: dict) -> dict: ...
    async def capabilities(self) -> dict: ...


class RemoteSessionAdapter(Protocol):
    async def status(self, device_id: str) -> dict: ...
    async def request_assisted_authentication(self, device_id: str) -> dict: ...


class CodexAdapter(Protocol):
    async def submit(self, workspace: str, instructions: str, approval_id: str) -> str: ...
    async def status(self, task_id: str) -> dict: ...
    async def cancel(self, task_id: str) -> None: ...


class VoiceAdapter(Protocol):
    async def transcribe(self, audio: bytes, content_type: str) -> str: ...
    async def synthesize(self, text: str, voice: str) -> bytes: ...


class DeviceAdapter(Protocol):
    async def status(self, device_id: str) -> dict: ...
    async def wake(self, device_id: str, approval_id: str) -> dict: ...
